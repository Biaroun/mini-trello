CREATE TABLE board (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100) NOT NULL,
    created_at TIMESTAMP    NOT NULL DEFAULT now()
);

CREATE TABLE board_column (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     VARCHAR(50) NOT NULL,
    position INT         NOT NULL CHECK (position >= 0),
    board_id BIGINT      NOT NULL REFERENCES board (id) ON DELETE CASCADE,
    CONSTRAINT uk_board_column_board_name UNIQUE (board_id, name)
);

CREATE TABLE card (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(100)  NOT NULL,
    description VARCHAR(1000),
    priority    VARCHAR(10)   NOT NULL DEFAULT 'MEDIUM' CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH')),
    due_date    DATE,
    position    INT           NOT NULL CHECK (position >= 0),
    column_id   BIGINT        NOT NULL REFERENCES board_column (id) ON DELETE CASCADE,
    created_at  TIMESTAMP     NOT NULL DEFAULT now()
);

-- Postgres n'indexe pas automatiquement les clés étrangères
CREATE INDEX idx_board_column_board_id ON board_column (board_id);
CREATE INDEX idx_card_column_id ON card (column_id);
